"""Evaluate each detector on eval/samples.jsonl and write a markdown report.

    python eval/run_eval.py [--samples FILE] [--out FILE] [--detectors none rules llm combined]

Samples are fed through the same `Guard` object the proxy uses (no subprocesses),
so the numbers describe the real decision logic: detector + policy together.
Detectors that need an API key are skipped, and reported as skipped, when
ANTHROPIC_API_KEY is not set. Nothing is estimated or filled in.
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
import time
from datetime import date
from pathlib import Path

import anyio

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from mcp_guard.config import load_policy  # noqa: E402
from mcp_guard.detectors import DETECTOR_NAMES, build_detector  # noqa: E402
from mcp_guard.detectors.llm import DEFAULT_MODEL, llm_available  # noqa: E402
from mcp_guard.guard import Guard  # noqa: E402
from mcp_guard.log import DecisionLog  # noqa: E402
from mcp_guard.session import SessionState  # noqa: E402

MALICIOUS_CATEGORIES = ["description_poisoning", "result_injection", "exfil_chain"]
NEEDS_API_KEY = {"llm", "combined"}


class ErrorCounting:
    """Wraps a detector to notice when it failed, so failures are not counted as catches."""

    def __init__(self, inner):
        self.inner, self.name, self.errors = inner, inner.name, 0

    async def check(self, text, surface):
        verdict = await self.inner.check(text, surface)
        self.errors += verdict.error
        return verdict


def load_samples(path: Path) -> list[dict]:
    lines = path.read_text(encoding="utf-8").splitlines()
    return [json.loads(line) for line in lines if line.strip()]


def _is_blocked_result(result: dict) -> bool:
    return bool(result.get("isError")) and "[MCP Guard]" in json.dumps(result)


async def run_sample(sample: dict, detector, policy, session_file: Path) -> bool:
    """Feed one sample through the guard. Returns True if the guard stopped it."""
    session = SessionState(session_file)
    session.reset()  # every sample is its own agent session
    guards: dict[str, Guard] = {}

    def guard_for(server: str) -> Guard:
        if server not in guards:
            guards[server] = Guard(server, policy, detector, DecisionLog(None), session)
        return guards[server]

    content = sample["content"]
    if sample["surface"] == "description":
        tool = content if isinstance(content, dict) else {"name": "tool", "description": content, "inputSchema": {"type": "object"}}
        return await guard_for("thirdparty").filter_tools([tool]) == []

    if sample["surface"] == "result":
        server, tool = sample.get("tool", "web.fetch").split(".", 1)
        result = {"content": [{"type": "text", "text": content}], "isError": False}
        return _is_blocked_result(await guard_for(server).check_result(tool, result))

    if sample["surface"] == "chain":
        for step in content["steps"]:
            server, tool = step["tool"].split(".", 1)
            if "arguments" in step:
                if await guard_for(server).check_call(tool, step["arguments"]) is not None:
                    return True
            else:
                result = {"content": [{"type": "text", "text": step["result"]}], "isError": False}
                if _is_blocked_result(await guard_for(server).check_result(tool, result)):
                    return True
        return False

    raise ValueError(f"sample {sample['id']}: unknown surface {sample['surface']!r}")


async def evaluate(detector_name: str, samples: list[dict], policy) -> dict:
    detector = ErrorCounting(build_detector(detector_name))
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for sample in samples:
            errors_before = detector.errors
            start = time.perf_counter()
            blocked = await run_sample(sample, detector, policy, Path(tmp) / "session.jsonl")
            rows.append({
                "sample": sample,
                "blocked": blocked,
                "ms": (time.perf_counter() - start) * 1000,
                "error": detector.errors > errors_before,
            })
    return {"detector": detector_name, "rows": rows}


def _rate(rows: list[dict]) -> str:
    if not rows:
        return "n/a"
    hits = sum(row["blocked"] for row in rows)
    return f"{hits}/{len(rows)} ({100 * hits / len(rows):.0f}%)"


def render(results: list[dict], skipped: list[str], samples: list[dict], samples_path: Path) -> str:
    counts = {category: sum(s["category"] == category for s in samples) for category in MALICIOUS_CATEGORIES + ["benign"]}
    out = [
        "# MCP Guard evaluation results",
        "",
        f"Generated by `eval/run_eval.py` on {date.today().isoformat()} from `{samples_path.name}` "
        f"({len(samples)} samples: " + ", ".join(f"{n} {c}" for c, n in counts.items()) + ").",
        "",
        "- **Block rate**: share of malicious samples the guard stopped (higher is better).",
        "- **False positives**: share of benign samples the guard stopped (lower is better).",
        "- **Avg latency**: mean time the guard spent per sample, detector included.",
        "- Samples where the detector itself failed are excluded from the rates and counted under *errors*.",
        "- `none` runs the action policy with no detector, as a baseline.",
        "",
        "| Detector | Description poisoning | Result injection | Exfil chain | All malicious | False positives | Avg latency | Errors |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for result in results:
        ok = [row for row in result["rows"] if not row["error"]]
        malicious = [row for row in ok if row["sample"]["malicious"]]
        benign = [row for row in ok if not row["sample"]["malicious"]]
        per_category = [_rate([row for row in malicious if row["sample"]["category"] == c]) for c in MALICIOUS_CATEGORIES]
        latency = sum(row["ms"] for row in ok) / len(ok) if ok else 0.0
        errors = len(result["rows"]) - len(ok)
        out.append(f"| `{result['detector']}` | " + " | ".join(per_category) + f" | {_rate(malicious)} | {_rate(benign)} | {latency:.2f} ms | {errors} |")
    for name in skipped:
        out.append(f"| `{name}` | skipped | skipped | skipped | skipped | skipped | skipped | - |")

    if skipped:
        out += ["", f"**Skipped: {', '.join(f'`{n}`' for n in skipped)}.** ANTHROPIC_API_KEY was not set when this report was generated, "
                "so detectors that call the LLM were not run. No numbers are reported for them. "
                f"Set ANTHROPIC_API_KEY (and optionally MCP_GUARD_LLM_MODEL, default `{DEFAULT_MODEL}`) and run the script again."]

    out += ["", "## Missed attacks (malicious samples that got through)", ""]
    for result in results:
        missed = [row["sample"] for row in result["rows"] if row["sample"]["malicious"] and not row["blocked"] and not row["error"]]
        out.append(f"### `{result['detector']}`: {len(missed)} missed")
        out += [f"- `{s['id']}` ({s['category']}): {s['note']}" for s in missed] or ["- none"]
        out.append("")

    out += ["## False positives (benign samples that were stopped)", ""]
    for result in results:
        wrong = [row["sample"] for row in result["rows"] if not row["sample"]["malicious"] and row["blocked"] and not row["error"]]
        out.append(f"### `{result['detector']}`: {len(wrong)} false positives")
        out += [f"- `{s['id']}` ({s['surface']}): {s['note']}" for s in wrong] or ["- none"]
        out.append("")

    out += [
        "## How to read this",
        "",
        "- The seed set is tiny (5 samples per category) and was written by the author of the rules. "
        "Treat the numbers as a smoke test of the harness, not as a measurement of real-world accuracy.",
        "- For `description` and `result` samples only the detector can block, so `none` scores 0 there by construction.",
        "- For `exfil_chain` samples the policy can block without any detector, but only if the content came from a tool "
        "listed under `untrusted_sources` in `eval/policy.yaml`.",
        "",
    ]
    return "\n".join(out)


async def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--samples", type=Path, default=ROOT / "eval" / "samples.jsonl")
    parser.add_argument("--out", type=Path, default=ROOT / "eval" / "results.md")
    parser.add_argument("--detectors", nargs="+", default=list(DETECTOR_NAMES), choices=DETECTOR_NAMES)
    args = parser.parse_args()

    samples = load_samples(args.samples)
    policy = load_policy(ROOT / "eval" / "policy.yaml")
    results, skipped = [], []
    for name in args.detectors:
        if name in NEEDS_API_KEY and not llm_available():
            skipped.append(name)
            continue
        print(f"running detector '{name}' on {len(samples)} samples...", file=sys.stderr)
        results.append(await evaluate(name, samples, policy))

    report = render(results, skipped, samples, args.samples)
    args.out.write_text(report, encoding="utf-8")
    print(report)
    print(f"(written to {args.out})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(anyio.run(main))
